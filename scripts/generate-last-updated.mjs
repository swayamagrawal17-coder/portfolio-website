// Writes src/lib/lastUpdated.ts from the latest git commit date, so the
// footer's "Updated ..." text always reflects the commit that produced the
// current deployment. Runs automatically before `dev` and `build` (see the
// "predev"/"prebuild" scripts in package.json). If git isn't available for
// some reason, the previously committed value in lastUpdated.ts is left as
// a safe fallback instead of the build failing.
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.join(__dirname, '..');
const outFile = path.join(repoRoot, 'src', 'lib', 'lastUpdated.ts');

function getLastCommitDate() {
  try {
    return execSync('git log -1 --date="format:%b %Y" --format=%cd', {
      cwd: repoRoot,
      encoding: 'utf8',
    }).trim() || null;
  } catch {
    return null;
  }
}

const lastUpdated = getLastCommitDate();

if (!lastUpdated) {
  const hadExisting = existsSync(outFile) && readFileSync(outFile, 'utf8').includes('LAST_UPDATED');
  console.warn(
    `[generate-last-updated] could not read git history, leaving ${hadExisting ? 'existing' : 'default'} src/lib/lastUpdated.ts as-is`
  );
  process.exit(0);
}

const contents = `// Auto-generated by scripts/generate-last-updated.mjs from the latest git
// commit date, right before \`dev\`/\`build\` runs. Do not edit by hand; the
// value here is only what happened to be committed last.
export const LAST_UPDATED = ${JSON.stringify(lastUpdated)};
`;

writeFileSync(outFile, contents);
console.log(`[generate-last-updated] wrote "${lastUpdated}" to ${path.relative(repoRoot, outFile)}`);
